LANGS = ["en", "tr"]


def esc(s: str) -> str:
    s = s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    s = s.replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if s[:1] == " " or s[-1:] == " ":
        s = '"' + s + '"'
    if s.startswith("@") or s.startswith("?"):
        s = "\\" + s
    return s


def main():
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "app", "src", "main", "res")
    for i, lang in enumerate(LANGS):
        folder = "values" if i == 0 else "values-" + lang
        os.makedirs(os.path.join(root, folder), exist_ok=True)
        out = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- tools/strings.py ile üretilir; elle düzenleme -->", "<resources>"]
        for k, v in S.items():
            fmt = ' formatted="false"' if "%" in v[i] and "%1$" not in v[i] and "%%" not in v[i] else ""
            out.append('    <string name="%s"%s>%s</string>' % (k, fmt, esc(v[i])))
        for k, v in PLURALS.items():
            out.append('    <plurals name="%s">' % k)
            for q, t in v[i].items():
                out.append('        <item quantity="%s">%s</item>' % (q, esc(t)))
            out.append("    </plurals>")
        out.append("</resources>")
        with open(os.path.join(root, folder, "strings.xml"), "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(out) + "\n")
    print("ok", len(S), "strings")


if __name__ == "__main__":
    main()
